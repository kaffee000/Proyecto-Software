-- Encola avisos cuando una actividad llena vuelve a tener cupos y registra
-- los recordatorios de asistencia de las inscripciones activas.

alter table public.inscripciones
    add column if not exists asistencia_estado text not null default 'pendiente',
    add column if not exists asistencia_token_hash text,
    add column if not exists asistencia_token_expira_at timestamptz,
    add column if not exists recordatorio_enviado_at timestamptz,
    add column if not exists recordatorio_procesando_at timestamptz,
    add column if not exists recordatorio_intentos integer not null default 0,
    add column if not exists recordatorio_ultimo_error text;

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'inscripciones_asistencia_estado_valido'
          and conrelid = 'public.inscripciones'::regclass
    ) then
        alter table public.inscripciones
            add constraint inscripciones_asistencia_estado_valido
            check (asistencia_estado in ('pendiente', 'confirmada'));
    end if;
end;
$$;

create unique index if not exists inscripciones_asistencia_token_idx
    on public.inscripciones (asistencia_token_hash)
    where asistencia_token_hash is not null;

create table if not exists public.notificaciones_cupo (
    id bigint generated by default as identity primary key,
    actividad_id uuid not null references public.actividades (id) on delete cascade,
    user_id uuid not null references auth.users (id) on delete cascade,
    creada_at timestamptz not null default now(),
    estado text not null default 'pendiente'
        check (estado in ('pendiente', 'procesando', 'enviado', 'fallido', 'cancelado')),
    intentos integer not null default 0 check (intentos >= 0),
    procesando_at timestamptz,
    enviado_at timestamptz,
    ultimo_error text
);

create index if not exists notificaciones_cupo_pendientes_idx
    on public.notificaciones_cupo (estado, id);

alter table public.notificaciones_cupo enable row level security;
revoke all on table public.notificaciones_cupo from anon, authenticated;
grant select on table public.actividades, public.vecinos, public.inscripciones to service_role;
grant select, insert, update on table public.notificaciones_cupo to service_role;
grant usage, select on sequence public.notificaciones_cupo_id_seq to service_role;

-- Solo el servidor de notificaciones puede leer perfiles y reclamar trabajos.
create or replace function public.reclamar_notificaciones_cupo(p_limite integer default 50)
returns table (
    notificacion_id bigint,
    actividad_id uuid,
    user_id uuid,
    correo text,
    primer_nombre text,
    actividad_nombre text,
    actividad_fecha timestamptz,
    lugar text,
    cupos_totales integer,
    cupos_ocupados integer,
    actividad_estado text,
    correo_verificado boolean,
    favorito_activo boolean,
    ya_inscrito boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_limite integer := greatest(1, least(coalesce(p_limite, 50), 200));
begin
    return query
    with candidatos as (
        select n.id
        from public.notificaciones_cupo n
        where n.intentos < 5
          and (
              n.estado = 'pendiente'
              or (n.estado = 'procesando' and n.procesando_at < now() - interval '15 minutes')
          )
        order by n.id
        for update of n skip locked
        limit v_limite
    ), reclamadas as (
        update public.notificaciones_cupo n
        set estado = 'procesando',
            intentos = n.intentos + 1,
            procesando_at = now(),
            ultimo_error = null
        from candidatos c
        where n.id = c.id
        returning n.id, n.actividad_id, n.user_id
    )
    select r.id,
           r.actividad_id,
           r.user_id,
           v.correo,
           v.primer_nombre,
           a.nombre,
           a.fecha,
           a.lugar,
           a.cupos_totales,
           a.cupos_ocupados,
           a.estado,
           coalesce(v.correo_verificado, false),
           (f.user_id is not null),
           (i.user_id is not null)
    from reclamadas r
    join public.actividades a on a.id = r.actividad_id
    left join public.vecinos v on v.user_id = r.user_id
    left join public.actividad_favoritos f on f.actividad_id = r.actividad_id and f.user_id = r.user_id
    left join public.inscripciones i on i.actividad_id = r.actividad_id and i.user_id = r.user_id;
end;
$$;

create or replace function public.finalizar_notificacion_cupo(
    p_notificacion_id bigint,
    p_resultado text,
    p_error text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    if p_resultado is null or p_resultado not in ('enviado', 'no_disponible', 'error') then
        raise exception 'Resultado de notificación no válido';
    end if;

    update public.notificaciones_cupo n
    set estado = case
            when p_resultado = 'enviado' then 'enviado'
            when p_resultado = 'no_disponible' then 'cancelado'
            when n.intentos >= 5 then 'fallido'
            else 'pendiente'
        end,
        enviado_at = case when p_resultado = 'enviado' then now() else null end,
        procesando_at = null,
        ultimo_error = case when p_resultado = 'error' then left(coalesce(p_error, 'Error de envío'), 500) else null end
    where n.id = p_notificacion_id;
end;
$$;

-- Reclama recordatorios por usuario e inscripción. El hash del token se guarda
-- antes de mandar el correo; una concesión vencida se puede recuperar tras 15 min.
create or replace function public.listar_recordatorios_asistencia(p_hasta timestamptz)
returns table (actividad_id uuid, user_id uuid)
language sql
security definer
set search_path = ''
as $$
    select i.actividad_id, i.user_id
    from public.inscripciones i
    join public.actividades a on a.id = i.actividad_id
    where i.asistencia_estado = 'pendiente'
      and i.recordatorio_enviado_at is null
      and i.recordatorio_intentos < 5
      and a.fecha > now()
      and a.fecha <= p_hasta
      and exists (
          select 1 from public.vecinos v
          where v.user_id = i.user_id and v.correo_verificado
      )
      and (
          i.recordatorio_procesando_at is null
          or i.recordatorio_procesando_at < now() - interval '15 minutes'
      )
    order by a.fecha, i.actividad_id, i.user_id
    limit 200;
$$;

create or replace function public.reclamar_recordatorio_asistencia(
    p_actividad_id uuid,
    p_user_id uuid,
    p_token_hash text
)
returns table (
    correo text,
    primer_nombre text,
    actividad_nombre text,
    actividad_fecha timestamptz,
    lugar text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
    if p_token_hash is null or length(p_token_hash) <> 64 then
        return;
    end if;

    return query
    with reclamadas as (
        update public.inscripciones i
        set asistencia_token_hash = p_token_hash,
            asistencia_token_expira_at = a.fecha,
            recordatorio_procesando_at = now(),
            recordatorio_intentos = i.recordatorio_intentos + 1,
            recordatorio_ultimo_error = null
        from public.actividades a
        where i.actividad_id = p_actividad_id
          and i.user_id = p_user_id
          and a.id = i.actividad_id
          and i.asistencia_estado = 'pendiente'
          and i.recordatorio_enviado_at is null
          and i.recordatorio_intentos < 5
          and a.fecha > now()
          and a.fecha <= now() + interval '24 hours'
          and exists (
              select 1 from public.vecinos v
              where v.user_id = i.user_id and v.correo_verificado
          )
          and (
              i.recordatorio_procesando_at is null
              or i.recordatorio_procesando_at < now() - interval '15 minutes'
          )
        returning i.actividad_id, i.user_id
    )
    select v.correo, v.primer_nombre, a.nombre, a.fecha, a.lugar
    from reclamadas r
    join public.vecinos v on v.user_id = r.user_id and v.correo_verificado
    join public.actividades a on a.id = r.actividad_id;
end;
$$;

create or replace function public.finalizar_recordatorio_asistencia(
    p_actividad_id uuid,
    p_user_id uuid,
    p_enviado boolean,
    p_error text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    update public.inscripciones i
    set recordatorio_enviado_at = case when p_enviado then now() else null end,
        recordatorio_procesando_at = null,
        asistencia_token_hash = case when p_enviado then i.asistencia_token_hash else null end,
        asistencia_token_expira_at = case when p_enviado then i.asistencia_token_expira_at else null end,
        recordatorio_ultimo_error = case when p_enviado then null else left(coalesce(p_error, 'Error de envío'), 500) end
    where i.actividad_id = p_actividad_id
      and i.user_id = p_user_id;
end;
$$;

-- El hash del enlace de asistencia es un secreto: solo se consulta desde el servidor.
create or replace function public.responder_confirmacion_asistencia(
    p_token_hash text,
    p_respuesta text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_actividad_id uuid;
    v_user_id uuid;
    v_estado text;
    v_expira_at timestamptz;
    v_nombre text;
    v_cupos_disponibles integer;
begin
    if p_token_hash is null
       or length(p_token_hash) <> 64
       or p_respuesta is null
       or p_respuesta not in ('si', 'no') then
        return pg_catalog.jsonb_build_object('status', 'solicitud_no_valida');
    end if;

    -- Lee primero sin bloquear para respetar el orden actividad -> inscripción
    -- usado por las otras funciones que cambian la capacidad.
    select i.actividad_id
    into v_actividad_id
    from public.inscripciones i
    where i.asistencia_token_hash = p_token_hash;

    if not found then
        return pg_catalog.jsonb_build_object('status', 'enlace_no_valido');
    end if;

    perform 1
    from public.actividades a
    where a.id = v_actividad_id
    for update;

    if not found then
        return pg_catalog.jsonb_build_object('status', 'enlace_no_valido');
    end if;

    select i.user_id, i.asistencia_estado, i.asistencia_token_expira_at
    into v_user_id, v_estado, v_expira_at
    from public.inscripciones i
    where i.actividad_id = v_actividad_id
      and i.asistencia_token_hash = p_token_hash
    for update;

    if not found then
        return pg_catalog.jsonb_build_object('status', 'enlace_no_valido');
    end if;

    if v_estado = 'confirmada' then
        return pg_catalog.jsonb_build_object('status', 'ya_confirmada');
    end if;

    if v_expira_at is null or v_expira_at <= now() then
        return pg_catalog.jsonb_build_object('status', 'enlace_vencido');
    end if;

    if p_respuesta = 'si' then
        update public.inscripciones
        set asistencia_estado = 'confirmada'
        where actividad_id = v_actividad_id and user_id = v_user_id;

        return pg_catalog.jsonb_build_object('status', 'asistencia_confirmada');
    end if;

    perform pg_catalog.set_config('muni.no_notificar_user_id', v_user_id::text, true);
    delete from public.inscripciones
    where actividad_id = v_actividad_id and user_id = v_user_id;

    if not found then
        return pg_catalog.jsonb_build_object('status', 'inscripcion_ya_liberada');
    end if;

    update public.actividades
    set cupos_ocupados = greatest(0, cupos_ocupados - 1)
    where id = v_actividad_id
    returning nombre, cupos_totales - cupos_ocupados
    into v_nombre, v_cupos_disponibles;

    return pg_catalog.jsonb_build_object(
        'status', 'cupo_liberado',
        'actividad', v_nombre,
        'cupos_disponibles', v_cupos_disponibles
    );
end;
$$;

-- Envía una notificación solo cuando el cambio hace que una actividad llena y
-- activa vuelva a tener disponibilidad. Los favoritos deben seguir vigentes y
-- el usuario no puede estar ya inscrito.
create or replace function public.notificar_favoritos_cupo_liberado()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_usuario_excluido uuid := coalesce(
        nullif(pg_catalog.current_setting('muni.no_notificar_user_id', true), '')::uuid,
        auth.uid()
    );
begin
    if old.estado = 'activo'
       and new.estado = 'activo'
       and old.cupos_ocupados >= old.cupos_totales
       and new.cupos_ocupados < new.cupos_totales then
        insert into public.notificaciones_cupo (actividad_id, user_id)
        select new.id, f.user_id
        from public.actividad_favoritos f
        join public.vecinos v on v.user_id = f.user_id and v.correo_verificado
        where f.actividad_id = new.id
          and f.user_id is distinct from v_usuario_excluido
          and not exists (
              select 1
              from public.inscripciones i
              where i.actividad_id = new.id
                and i.user_id = f.user_id
          );
    end if;

    return new;
end;
$$;

drop trigger if exists actividades_notificar_cupo_liberado on public.actividades;
create trigger actividades_notificar_cupo_liberado
    after update of cupos_totales, cupos_ocupados, estado on public.actividades
    for each row
    execute function public.notificar_favoritos_cupo_liberado();

-- Cancelar también toma primero el bloqueo de actividad para serializarse con
-- las inscripciones y la respuesta al recordatorio de asistencia.
create or replace function public.cancelar_inscripcion_actividad(p_actividad_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_user_id uuid := auth.uid();
    v_nombre text;
    v_cupos_disponibles integer;
begin
    if v_user_id is null then
        return pg_catalog.jsonb_build_object('status', 'no_autenticado');
    end if;

    select a.nombre
    into v_nombre
    from public.actividades a
    where a.id = p_actividad_id
    for update;

    if not found then
        return pg_catalog.jsonb_build_object('status', 'actividad_no_encontrada');
    end if;

    delete from public.inscripciones i
    where i.actividad_id = p_actividad_id
      and i.user_id = v_user_id;

    if not found then
        return pg_catalog.jsonb_build_object('status', 'no_inscrito');
    end if;

    update public.actividades a
    set cupos_ocupados = greatest(0, a.cupos_ocupados - 1)
    where a.id = p_actividad_id
    returning a.nombre, a.cupos_totales - a.cupos_ocupados
    into v_nombre, v_cupos_disponibles;

    return pg_catalog.jsonb_build_object(
        'status', 'cancelada',
        'actividad', v_nombre,
        'cupos_disponibles', v_cupos_disponibles
    );
end;
$$;

